/**
 * The rules text of what a leader gains from the campaign book.
 *
 * ## Two sources, chosen per entry — v0.37.0, owner decision
 *
 * Until v0.37.0 this text sat behind a gate: prove you own the book, and see
 * only what your arsenal held. The owner retired the gate (it could not be
 * enforced, audit v0.28.1 H2) and asked for two things instead:
 *
 *   1. **Show what a leader gains** — the actions, abilities, triggers and
 *      modifiers off the six advancement tables.
 *   2. **Read it from BiggerHat wherever BiggerHat has it.** Many advancements
 *      are the same trigger or action as one printed on a card. Those keys are
 *      listed in `data/bookSources.js` (identifiers only, generated by
 *      `scripts/book-sources.mjs` after checking the stats and text agree) and
 *      fetched live through the register proxy, exactly like card text (§4).
 *
 * Everything else comes from `book_text` in D1 through `POST /api/book`, for
 * any signed-in player. Not from this repository: a public commit cannot be
 * un-published, and if Wyrd asks, emptying one table switches it off.
 *
 * ## What an entry looks like
 *
 * `book_text.text` holds one JSON object per key, written by
 * `scripts/book-extract.mjs`: `{ kind, name, description, ... }`, where `kind`
 * is `action`, `ability`, `trigger`, `modifier` or `totem`, and an action
 * carries the same fields `rules.js`'s `toAction` produces. A value that is not
 * JSON (a hand-typed entry) reads as `{ kind: 'text', description }`.
 *
 * ## It is display-only, and must stay that way
 *
 * Held in a module-level cache that dies with the tab, like `lib/rules.js`.
 * **Never write any of this into a campaign document, the JSON export, or
 * localStorage.**
 */
import { registry } from './api.js'
import { toAction, toAbility, toTrigger } from './rules.js'
import { BOOK_SOURCES } from '../data/bookSources.js'
import { ADVANCEMENT_TABLES } from '../data/advancements.js'

/** Everything fetched this session, by key. Dies with the tab. */
const cache = new Map()
/** Keys already asked about and answered for — including the empty answers. */
const asked = new Set()
/** The request each key is waiting on, while it is out. */
const inflight = new Map()
let localFile = null

/**
 * The key for one advancement row.
 *
 * Table, value and name together, because none of the three is unique alone:
 * "Skill Boost" is printed three times on the attack table at different values,
 * and value 9 on the action table carries four different options. Getting this
 * wrong is how the name-keyed select fixed in v0.22.2 recorded the wrong row
 * for several versions.
 */
export function advancementKey(tableId, entry) {
  if (!tableId || !entry?.name) return null
  /**
   * `value` on a row from `data/advancements.js`, `tableValue` on one that was
   * *recorded* on a leader — the same number under two names, because v0.22.2
   * had to call it something else to sit beside the flip that won it.
   *
   * Reading only `value` looked right against the data file and found nothing
   * at all on a real record, which is where it was caught: the scaffold is
   * generated from one shape and every lookup happens against the other.
   */
  const value = entry.value ?? entry.tableValue ?? '?'
  return `advancement:${tableId}:${value}:${entry.name}`
}

/** The key for one piece of equipment. Its id is already unique. */
export function equipmentKey(id) {
  return id ? `equipment:${id}` : null
}

/**
 * The key for one injury upgrade, by its printed name.
 *
 * By name because nothing else is shared by all three ends. The injury table's
 * rows carry no id, an arsenal's injury row has a random `inj_…` id, and an
 * upgrade's text is the same whichever flip attached it (audit v0.28.1 L5).
 */
export function injuryKey(name) {
  return name ? `injury:${name}` : null
}

/** A totem's own ability or action, as `data/bookSources.js` keys it. */
export function totemPartKey(totemKey, kind, name) {
  return `${totemKey}|${kind}:${name}`
}

/** `{{ram}}` → `Ram`, the way the register spells a trigger's suit. */
const SUIT = { crow: 'Crow', mask: 'Mask', ram: 'Ram', tome: 'Tome', stone: 'Soulstone' }
const DEFENCE = {
  fortitude: 'Fortitude', warding: 'Warding', unusual: 'Unusual',
  physical_defense: 'Fortitude', magical_defense: 'Warding', unusual_defense: 'Unusual',
}
const token = (s) => (String(s || '').match(/\{\{(\w+)\}\}/) || [])[1] || null

/**
 * A book entry, in the shapes `RulesText` already renders.
 *
 * Exported for the tests. The book's own stat cells arrive as strings ("5",
 * "5{{+}}", "*"), which `statLine` prints as they are.
 */
export function fromBook(raw) {
  if (typeof raw !== 'string' || !raw.trim()) return null
  let e
  try {
    e = raw.trim().startsWith('{') ? JSON.parse(raw) : null
  } catch {
    e = null
  }
  if (!e) return { kind: 'text', source: 'book', description: raw.trim() }

  if (e.kind === 'action') {
    return {
      ...toAction({
        name: e.name,
        type: null,
        is_signature: e.isSignature,
        stone_cost: e.stoneCost,
        range: e.range,
        range_type_label: e.rangeTypeLabel,
        stat: e.stat,
        resisted_by: e.resistedBy,
        target_number: e.targetNumber,
        damage: e.damage,
        description: e.description,
      }),
      kind: 'action',
      source: 'book',
    }
  }
  if (e.kind === 'ability') {
    return {
      ...toAbility({ name: e.name, description: e.description }),
      kind: 'ability',
      defence: DEFENCE[token(e.suits)] || null,
      source: 'book',
    }
  }
  if (e.kind === 'trigger') {
    return {
      ...toTrigger({ name: e.name, suits: SUIT[token(e.suits)] || null, description: e.description }),
      kind: 'trigger',
      source: 'book',
    }
  }
  if (e.kind === 'totem') {
    // A part the register carries is loaded as `{ kind, name, isSignature,
    // fromRegister: true }` and filled in by `ensureBookText`.
    const part = (a, kind) => (a.fromRegister
      ? { kind, name: a.name, isSignature: Boolean(a.isSignature), source: 'pending' }
      : fromBook(JSON.stringify({ ...a, kind })))
    return {
      kind: 'totem',
      source: 'book',
      name: e.name,
      description: e.description || '',
      abilities: (e.abilities || []).map((a) => part(a, 'ability')),
      actions: (e.actions || []).map((a) => part(a, 'action')),
    }
  }
  return { kind: e.kind || 'text', source: 'book', name: e.name, description: e.description || '' }
}

/** A register record, in the same shapes. */
export function fromRegister(from, record, bookEntry) {
  if (!record) return null
  if (from === 'actions') {
    const action = { ...toAction(record), kind: 'action', source: 'biggerhat' }
    // The register's `is_signature` is wrong for printed signature actions
    // (lib/signature.js), so the book's glyph decides it: `isSignature` on a
    // row of `data/advancements.js` or on a totem part. Its triggers belong to
    // whichever card BiggerHat filed it under, and a leader taking the action
    // does not get them (§4).
    action.isSignature = Boolean(bookEntry?.isSignature)
    action.triggers = []
    return action
  }
  if (from === 'abilities') {
    return {
      ...toAbility(record),
      kind: 'ability',
      defence: DEFENCE[record.defensive_ability_type] || null,
      source: 'biggerhat',
    }
  }
  if (from === 'triggers') {
    return { ...toTrigger(record), kind: 'trigger', source: 'biggerhat' }
  }
  return null
}

/**
 * The register's copy, or null if it cannot be reached. Never throws.
 *
 * In `npm run dev` a miss falls back to the local `book/book.json`, which holds
 * every row, so the owner can work on screens with the register unreachable.
 */
async function fromBiggerHat(key, bookEntry) {
  const where = BOOK_SOURCES[key]
  if (!where) return null
  try {
    return fromRegister(where.from, await registry.entry(where.from, where.slug), bookEntry)
  } catch {
    if (key.includes('|')) return null
    return fromBook((await readLocalFile())[key])
  }
}

/**
 * The dev-only local copy, `book/book.json`, read once.
 *
 * `npm run dev` serves no Functions (§10), so `/api/book` cannot answer there.
 * Vite's dev server serves the project root, which is where this file lives;
 * a production build never contains it, because it is not under `public/`.
 */
async function readLocalFile() {
  if (localFile) return localFile
  if (!import.meta.env?.DEV) return {}
  try {
    const res = await fetch('/book/book.json')
    if (!res.ok) return {}
    const json = await res.json()
    localFile = json && typeof json === 'object' ? json : {}
    return localFile
  } catch {
    return {}
  }
}

async function fromServer(keys) {
  if (keys.length === 0) return {}
  try {
    const res = await fetch('/api/book', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ keys }),
    })
    if (res.ok) return (await res.json()) || {}
  } catch {
    // No Functions (dev), offline, signed out — all fall through to the file.
  }
  const file = await readLocalFile()
  const out = {}
  for (const key of keys) if (file[key]) out[key] = file[key]
  return out
}

/**
 * Each advancement row's printed facts, by key — for the signature glyph on a
 * row read from the register, whose own flag is wrong (lib/signature.js).
 */
const ROWS = new Map(ADVANCEMENT_TABLES.flatMap((t) => (t.entries || [])
  .map((e) => [advancementKey(t.id, e), e])))

/**
 * Fetch these entries, skipping any already answered for.
 *
 * Resolves to the accumulated cache. An entry neither source can supply is
 * simply absent, and the screen reads as it did before: the name and the page.
 *
 * A key BiggerHat carries is never asked of the server: its row is not loaded
 * into `book_text` at all (`scripts/book-to-sql.mjs` skips it), so the app
 * hosts only what the register lacks. If the register is down, that entry
 * shows its name and page until it is back, as card text does (§6). For a
 * totem, each of its own abilities and actions the register carries is
 * fetched from it the same way.
 */
export async function ensureBookText(keys = []) {
  const all = [...new Set(keys.filter(Boolean))]
  const wanted = all.filter((k) => !asked.has(k))

  // Marked before the request rather than after: two components mounting
  // together must not both ask for the same keys. A caller whose keys are
  // already in flight waits for them instead of returning the cache early —
  // otherwise React's development double-mount discards the first request and
  // the second resolves to nothing, which is how no text ever appeared.
  const request = wanted.length ? fetchEntries(wanted) : null
  for (const key of wanted) {
    asked.add(key)
    inflight.set(key, request)
  }
  await Promise.all([...new Set(all.map((k) => inflight.get(k)).filter(Boolean))])
  return cache
}

async function fetchEntries(wanted) {
  const raw = await fromServer(wanted.filter((k) => !BOOK_SOURCES[k]))

  await Promise.all(wanted.map(async (key) => {
    let entry = BOOK_SOURCES[key]
      ? await fromBiggerHat(key, ROWS.get(key))
      : fromBook(raw[key])
    if (entry?.kind === 'totem') {
      const swap = async (part, kind) => (await fromBiggerHat(totemPartKey(key, kind, part.name), part)) || part
      entry = {
        ...entry,
        abilities: await Promise.all(entry.abilities.map((a) => swap(a, 'ability'))),
        actions: await Promise.all(entry.actions.map((a) => swap(a, 'action'))),
      }
    }
    if (entry) cache.set(key, entry)
    inflight.delete(key)
  }))
}

/** The entry for a key, or null. `book` is the map from the hook. */
export function entryFor(book, key) {
  if (!book || !key) return null
  const value = book instanceof Map ? book.get(key) : book[key]
  return value && typeof value === 'object' ? value : null
}

/** Testing seam — the cache is module-level and would leak between cases. */
export function resetBookCache() {
  cache.clear()
  asked.clear()
  inflight.clear()
  localFile = null
}
