#!/usr/bin/env node
/**
 * Turn `book/book.json` into SQL for the `book_text` table.
 *
 *   node scripts/book-to-sql.mjs > book.sql
 *   npx wrangler d1 execute hodgepodge-hearthside --remote --file=./book.sql
 *   rm book.sql
 *
 * **Only what BiggerHat does not carry.** A key in `src/data/bookSources.js` is
 * read live from the register by the app, so its row is left out, and a totem's
 * register-carried abilities and actions are loaded as a name only. Re-run
 * `scripts/book-sources.mjs` first if the register has changed. The SQL deletes
 * every row it is not loading, so a key that has moved to the register stops
 * being hosted here.
 *
 * **There is deliberately no write endpoint.** Loading by hand means the table
 * has no write surface reachable from the app.
 *
 * `d1 execute --file` is atomic — a file whose last statement fails rolls the
 * whole thing back — so a half-loaded book is not a state that can happen.
 *
 * Output goes to stdout, and `book.sql` is gitignored. Delete it when you are
 * done: it is the book in the clear.
 */

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const source = path.join(root, 'book', 'book.json')

if (!fs.existsSync(source)) {
  console.error('No book/book.json. Run `node scripts/book-extract.mjs` first.')
  process.exit(1)
}

let book
try {
  book = JSON.parse(fs.readFileSync(source, 'utf8'))
} catch {
  console.error('book/book.json is not valid JSON.')
  process.exit(1)
}

const { BOOK_SOURCES } = await import(pathToFileURL(path.join(root, 'src/data/bookSources.js')).href)
const fromRegister = (key, kind, name) => Boolean(BOOK_SOURCES[`${key}|${kind}:${name}`])

/** A totem's parts the register carries, cut down to what says which they are. */
function hostedText(key, text) {
  if (!text.startsWith('{')) return text
  const entry = JSON.parse(text)
  if (entry.kind !== 'totem') return text
  const cut = (kind) => (a) => (fromRegister(key, kind, a.name)
    ? { name: a.name, isSignature: a.isSignature || undefined, fromRegister: true }
    : a)
  return JSON.stringify({
    ...entry,
    abilities: (entry.abilities || []).map(cut('ability')),
    actions: (entry.actions || []).map(cut('action')),
  })
}

const rows = Object.entries(book)
  .filter(([key, value]) => !key.endsWith('::page') && typeof value === 'string' && value.trim())
  .filter(([key]) => !BOOK_SOURCES[key])
  .map(([key, value]) => [key, hostedText(key, value.trim())])

/** SQLite string literal: double the single quotes and nothing else. */
const q = (s) => `'${String(s).replace(/'/g, "''")}'`

const now = Date.now()
const lines = [
  '-- Generated by scripts/book-to-sql.mjs. Do not commit this file.',
  `-- ${rows.length} entries; ${Object.keys(BOOK_SOURCES).length} read from BiggerHat instead.`,
  '',
  rows.length
    ? `DELETE FROM book_text WHERE key NOT IN (${rows.map(([k]) => q(k)).join(', ')});`
    : 'DELETE FROM book_text;',
]

for (const [key, text] of rows) {
  lines.push(
    `INSERT INTO book_text (key, text, updated_at) VALUES (${q(key)}, ${q(text)}, ${now})`
    + '  ON CONFLICT(key) DO UPDATE SET text = excluded.text, updated_at = excluded.updated_at;'
  )
}

console.log(lines.join('\n'))
