#!/usr/bin/env node
/**
 * Turn your local `challenges.json` into SQL for the `book_challenges` table.
 *
 *   node scripts/book-challenges.mjs > challenges.sql
 *   npx wrangler d1 execute hodgepodge-hearthside --remote --file=./challenges.sql
 *   rm challenges.sql
 *
 * **The plaintext answer never leaves this machine.** It is hashed here, by the
 * same `normaliseAnswer` + `hashAnswer` the server uses, so `book_challenges`
 * cannot be mined for the content it protects — and neither can the repository,
 * since `challenges.json` and `challenges.sql` are both gitignored.
 *
 * ## Writing a fair question
 *
 * The answer must NOT be findable in this public repo. `src/data/` publishes
 * every name, value, cost, page and suit, so "what is the barter rating of the
 * Gatling Gun?" proves nothing — it is one `git clone` away.
 *
 * What the repo does not have is the prose and the stat lines. The Silent
 * Catalogue alone carries 134 equipment stat blocks (Rg / Skl / Rst / TN / Dmg)
 * that appear nowhere in `src/data/equipment.js`. Those make good questions.
 *
 * Keep them short to answer and hard to guess. "What is the Dmg of X?" has
 * about a dozen plausible answers, which is why the server also limits
 * attempts — but a question with two plausible answers is a coin toss whatever
 * the limiter does.
 *
 * ## The file
 *
 *   [
 *     { "title": "the-silent-catalogue",
 *       "question": "In The Silent Catalogue's equipment tables, what is the Rg of the Flask?",
 *       "answer": "..." }
 *   ]
 *
 * `title` must match what `book_text.title` uses for the same book.
 */

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { webcrypto } from 'node:crypto'

// The store is written for the edge, where `crypto.subtle` is a global.
if (!globalThis.crypto) globalThis.crypto = webcrypto

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const source = path.join(root, 'challenges.json')

if (!fs.existsSync(source)) {
  console.error('No challenges.json at the repo root. See this file’s header for the shape.')
  process.exit(1)
}

const { hashAnswer, normaliseAnswer } = await import(
  pathToFileURL(path.join(root, 'functions', 'lib', 'bookStore.js')).href
)

let items
try {
  items = JSON.parse(fs.readFileSync(source, 'utf8'))
} catch {
  console.error('challenges.json is not valid JSON.')
  process.exit(1)
}

if (!Array.isArray(items) || items.length === 0) {
  console.error('challenges.json should be a non-empty array.')
  process.exit(1)
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`
const now = Date.now()
const lines = [
  '-- Generated by scripts/book-challenges.mjs. Do not commit this file.',
  `-- ${items.length} challenges. Answers are hashed; no plaintext here.`,
  '',
]

let n = 0
for (const item of items) {
  const { title, question, answer } = item || {}
  if (!title || !question || !answer) {
    console.error(`Skipping an entry missing title, question or answer: ${JSON.stringify(item)}`)
    continue
  }
  if (!normaliseAnswer(answer)) {
    console.error(`Skipping "${question}" — the answer normalises to nothing.`)
    continue
  }
  n += 1
  const id = `chal_${title}_${n}`
  lines.push(
    `INSERT INTO book_challenges (id, title, question, answer_hash, created_at)`
    + ` VALUES (${q(id)}, ${q(title)}, ${q(question)}, ${q(await hashAnswer(answer))}, ${now})`
    + `  ON CONFLICT(id) DO UPDATE SET question = excluded.question,`
    + ` answer_hash = excluded.answer_hash;`
  )
}

if (n === 0) {
  console.error('Nothing usable in challenges.json.')
  process.exit(1)
}

console.log(lines.join('\n'))
